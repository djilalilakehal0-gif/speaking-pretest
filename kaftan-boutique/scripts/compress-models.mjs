// Compresses the Blender GLB exports with glTF-Transform (Meshopt geometry compression, resampled
// normals/UVs quantization, deduplicated textures) and records the settings and sizes in
// public/models/COMPRESSION.md. Run after generate_kaftans.py:  npm run models:compress
import { execFileSync } from 'node:child_process'
import { readdirSync, statSync, renameSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = new URL('../public/models/', import.meta.url).pathname
const cli = new URL('../node_modules/.bin/gltf-transform', import.meta.url).pathname
const rows = []
for (const f of readdirSync(dir).filter((n) => /^kaftan-model-\d+\.glb$/.test(n)).sort()) {
  const src = join(dir, f)
  const tmp = join(dir, `.${f}.tmp.glb`)
  const before = statSync(src).size
  execFileSync(cli, [
    'optimize', src, tmp,
    '--compress', 'meshopt',
    '--texture-compress', 'false',
    '--texture-size', '512',
    '--simplify', 'false',
    '--instance', 'false',
    '--flatten', 'false',
    '--join', 'false',
  ], { stdio: 'inherit' })
  renameSync(tmp, src)
  const after = statSync(src).size
  rows.push(`| ${f} | ${(before / 1024).toFixed(0)} KB | ${(after / 1024).toFixed(0)} KB | ${((1 - after / before) * 100).toFixed(0)} % |`)
}
writeFileSync(
  join(dir, 'COMPRESSION.md'),
  `# Model compression record

Generated by \`scripts/compress-models.mjs\` (glTF-Transform ${execFileSync(cli, ['--version']).toString().trim()}).

Settings: \`gltf-transform optimize --compress meshopt --texture-compress false --texture-size 512 --simplify false --instance false --flatten false --join false\`

- Geometry: EXT_meshopt_compression + KHR_mesh_quantization (decoded in the browser by three.js' bundled Meshopt decoder; no CDN).
- Textures: one 512 px tiling satin-weave normal map (PNG) per model, unchanged.
- Simplification is off: silhouettes and folds stay exactly as modelled.

| File | Blender export | Compressed | Saved |
|---|---|---|---|
${rows.join('\n')}
`,
)
console.log(rows.join('\n'))
