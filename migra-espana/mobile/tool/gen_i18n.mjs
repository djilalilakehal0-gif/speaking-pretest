// Generates lib/i18n/strings.g.dart from the web app's dictionaries (single source of truth).
// Run from mobile/:  node --experimental-strip-types tool/gen_i18n.mjs
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, '../../web/src');
const out = join(here, '../lib/i18n/strings.g.dart');

const locales = ['es', 'en', 'fr', 'ar'];
const dicts = {};
for (const l of locales) dicts[l] = (await import(join(web, `i18n/${l}.ts`)))[l];
const { COUNTRY_CODES } = await import(join(web, 'lib/eligibility/countries.ts'));

const esc = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')}'`;

let dart = `// GENERATED by mobile/tool/gen_i18n.mjs from web/src/i18n and web/src/lib/eligibility/countries.ts.\n// Do not edit by hand: change the web dictionaries and re-run the generator.\n// ignore_for_file: lines_longer_than_80_chars\n\n`;

dart += 'const Map<String, Map<String, String>> dictionaries = {\n';
for (const l of locales) {
  dart += `  '${l}': {\n`;
  for (const [k, v] of Object.entries(dicts[l])) dart += `    ${esc(k)}: ${esc(v)},\n`;
  dart += '  },\n';
}
dart += '};\n\n';

// Country names from the same ICU data the web picker uses (Intl.DisplayNames), per locale.
const intl = { es: 'es-ES', en: 'en-GB', fr: 'fr-FR', ar: 'ar' };
dart += 'const Map<String, Map<String, String>> countryNames = {\n';
for (const l of locales) {
  const dn = new Intl.DisplayNames([intl[l]], { type: 'region' });
  dart += `  '${l}': {\n`;
  for (const c of COUNTRY_CODES) dart += `    '${c}': ${esc(dn.of(c) ?? c)},\n`;
  dart += '  },\n';
}
dart += '};\n';

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, dart);
console.log(`wrote ${out}: ${locales.map((l) => `${l}=${Object.keys(dicts[l]).length}`).join(' ')}, countries=${COUNTRY_CODES.length}`);
